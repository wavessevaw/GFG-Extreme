"""Builds py_modules/gfg_plugin/kedavra/hud_logo.py (the wolf in the in-game HUD) from
docs/img/logo.png, one RGBA bitmap per HUD scale.
  python3 tools/make_hud_logo.py [LOGO_PNG]
"""
import base64
import sys
import zlib
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
HUD_SIZES = {"0.88": 19, "1.32": 29, "1.76": 39}   # hud.SCALES


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "docs/img/logo.png"
    logo = Image.open(src).convert("RGBA")
    lines = ["# SPDX-License-Identifier: GPL-3.0-or-later",
             "# Generated by tools/make_hud_logo.py from docs/img/logo.png. Do not edit.",
             "# HUD scale -> (size in pixels, base64 of zlib-compressed RGBA rows).",
             "LOGO = {"]
    for scale, px in HUD_SIZES.items():
        im = logo.resize((px, px), Image.LANCZOS)
        lines.append(f'    "{scale}": ({px}, "{base64.b64encode(zlib.compress(im.tobytes(), 9)).decode()}"),')
    lines.append("}")
    (ROOT / "py_modules/gfg_plugin/kedavra/hud_logo.py").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
